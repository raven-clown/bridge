package review

import (
	"testing"

	"github.com/raven-clown/bridge/forge"
)

func TestCollapseRules(t *testing.T) {
	tests := []struct {
		path, patch, reason string
	}{
		{"go.sum", "@@ -1 +1 @@\n+x", "lock file"},
		{"web/package-lock.json", "@@ -1 +1 @@\n+x", "lock file"},
		{"Cargo.lock", "@@ -1 +1 @@\n+x", "lock file"},
		{"uv.lock", "@@ -1 +1 @@\n+x", "lock file"},
		{"vendor/x/y.go", "@@ -1 +1 @@\n+x", "generated"},
		{"web/dist/app.js", "@@ -1 +1 @@\n+x", "generated"},
		{"api/x.pb.go", "@@ -1 +1 @@\n+x", "generated"},
		{"x_gen.go", "@@ -1 +1 @@\n+x", "generated"},
		{"y.gen.go", "@@ -1 +1 @@\n+x", "generated"},
		{"app.min.js", "@@ -1 +1 @@\n+x", "generated"},
		{"mock.go", "@@ -0,0 +1,2 @@\n+// Code generated by mockgen. DO NOT EDIT.\n+package x", "generated"},
		{"main.go", "@@ -1 +1 @@\n+x", ""},
		{"notes.go", "@@ -0,0 +1 @@\n+// Code generated is a phrase here, edit freely", ""},
	}
	for _, tt := range tests {
		f, err := Parse(forge.FilePatch{Path: tt.path, Patch: tt.patch})
		if err != nil {
			t.Fatal(err)
		}
		Collapse(&f)
		if f.Collapsed != (tt.reason != "") || f.Reason != tt.reason {
			t.Errorf("%s: collapsed %v reason %q, want %q", tt.path, f.Collapsed, f.Reason, tt.reason)
		}
	}
}
